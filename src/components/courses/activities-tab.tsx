const TYPES: ActivityType[] = ["decision", "inspection", "simulator", "quick"];
const VOICE = { none: "Sin voz", pending: "Grabando la voz…", ready: "Con voz", failed: "La voz falló" } as const;
const JOB_POLL_MS = 3000;
const JOB_DONE = ["succeeded", "failed", "canceled"];

/** The interactive activities after each module's video: generated by the AI, reviewed and published here. */
export function ActivitiesTab({ course }: { course: CourseDetail }) {
  return (
    <div className="space-y-10">
      <SectionHeader
        title="Actividades"
        description="Juegos cortos después del video de cada módulo: una conversación con un cliente, una inspección visual, un simulador o un reto contra reloj. Las personas deben jugarlos (con cualquier puntaje) para completar el módulo."
      />
      {course.modules.length === 0 ? (
        <EmptyState
          icon={<Gamepad2 />}
          title="Primero agrega módulos"
          description="Las actividades se agregan a cada módulo."
        />
      ) : (
        course.modules.map((module) => (
          <ModuleActivities key={module.id} courseId={course.id} language={course.language} module={module} />
        ))
      )}
    </div>
  );
}

function ModuleActivities({ courseId, language, module }: { courseId: number; language: Language; module: ModuleAdmin }) {
  const queryClient = useQueryClient();
  const confirm = useConfirm();
  const { refreshCourse, refreshPeople } = useCourseCache();
  const key = activityKeys.module(module.id);
  const [jobId, setJobId] = useState<string | null>(null);
  const [editing, setEditing] = useState<ActivityAdmin | null>(null);
  const [trying, setTrying] = useState<{ activity: ActivityAdmin; session: number } | null>(null);
  const list = useQuery({
    queryKey: key,
    queryFn: () => activitiesApi.list(module.id),
    // While a voice is being recorded, its status updates by itself.
    refetchInterval: (query) =>
      query.state.data?.some((activity) => activity.voice_status === "pending") ? JOB_POLL_MS : false,
  });
  const job = useQuery({
    queryKey: ["jobs", jobId],
    queryFn: () => studioApi.job(jobId as string),
    enabled: Boolean(jobId),
    refetchInterval: (query) =>
      query.state.status === "error" || (query.state.data && JOB_DONE.includes(query.state.data.status))
        ? false
        : JOB_POLL_MS,
  });
  // The course's preview shows the published activities too.
  const refresh = () =>
    Promise.all([
      queryClient.invalidateQueries({ queryKey: key }),
      queryClient.invalidateQueries({ queryKey: courseKeys.preview(courseId) }),
    ]);
  // Unpublished or deleted: whoever only had it pending completed the module, so the course's progress changed
  // (participants, results, the course's counts; each person's courses in Equipo, and the panel).
  const refreshProgress = () =>
    Promise.all([queryClient.invalidateQueries({ queryKey: key }), refreshCourse(courseId), refreshPeople()]);

  useEffect(() => {
    const status = job.data?.status;
    if (!status || !JOB_DONE.includes(status)) return;
    if (status === "succeeded")
      toast.success(`La IA propuso las actividades de «${module.title}»: revísalas y publícalas.`);
    else toast.error(job.data?.error || "La IA no pudo proponer actividades.");
    setJobId(null);
    void refresh();
    // eslint-disable-next-line react-hooks/exhaustive-deps -- once per finished job
  }, [job.data?.status]);

  useEffect(() => {
    if (!job.isError) return;
    toastError(job.error);
    setJobId(null); // the job can't be followed: stop waiting on it
  }, [job.isError, job.error]);

  const generate = useMutation({
    mutationFn: () => activitiesApi.generate(module.id),
    onSuccess: (started) => setJobId(started.id),
    onError: toastError,
  });
  const create = useMutation({
    mutationFn: (type: ActivityType) => {
      const { title, intro, spec } = TEMPLATES[type];
      return activitiesApi.create(module.id, { type, title, intro, spec: spec as unknown as Record<string, unknown> });
    },
    onSuccess: (created) => {
      void refresh();
      setEditing(created);
    },
    onError: toastError,
  });
  const change = useMutation({
    mutationFn: ({ id, changes }: { id: number; changes: Parameters<typeof activitiesApi.update>[1] }) =>
      activitiesApi.update(id, changes),
    onSuccess: (_saved, { changes }) => (changes.status === "draft" ? refreshProgress() : refresh()),
    onError: toastError,
  });
  // Where a moved activity landed, for screen readers (the list shows it once the new order is saved).
  const [moved, setMoved] = useState("");
  const order = useMutation({
    mutationFn: ({ ids }: { ids: number[]; movedId: number }) => activitiesApi.order(module.id, ids),
    onSuccess: (saved, { movedId }) => {
      queryClient.setQueryData(key, saved);
      void queryClient.invalidateQueries({ queryKey: courseKeys.preview(courseId) });
      const at = saved.findIndex((activity) => activity.id === movedId);
      if (at >= 0) setMoved(`«${saved[at].title}» quedó en la posición ${at + 1} de ${saved.length}.`);
    },
    onError: toastError,
  });
  const remove = async (activity: ActivityAdmin) => {
    const ok = await confirm({
      title: `¿Eliminar «${activity.title}»?`,
      description: "Se borran también las partidas jugadas.",
      confirmLabel: "Eliminar",
      destructive: true,
    });
    if (!ok) return;
    try {
      await activitiesApi.remove(activity.id);
      await refreshProgress();
    } catch (error) {
      toastError(error);
    }
  };
  /** Publishing is immediate; unpublishing asks first: it may complete the module for people waiting only on it. */
  const toggleStatus = async (activity: ActivityAdmin) => {
    if (activity.status === "ready") {
      const ok = await confirm({
        title: `¿Despublicar «${activity.title}»?`,
        description:
          "Las personas dejan de verla. Quien solo tenía pendiente esta actividad completa el módulo, y eso no cambia si la vuelves a publicar.",
        confirmLabel: "Despublicar",
        destructive: true,
      });
      if (!ok) return;
    }
    change.mutate({ id: activity.id, changes: { status: activity.status === "ready" ? "draft" : "ready" } });
  };

  const activities = list.data ?? [];
  // After a move the arrow pressed takes the focus back, once the new order is on screen (the arrows wait meanwhile).
  const refocus = useRef<{ id: number; direction: -1 | 1 } | null>(null);
  const move = (index: number, direction: -1 | 1) => {
    const ids = activities.map((activity) => activity.id);
    const movedId = ids[index];
    [ids[index], ids[index + direction]] = [ids[index + direction], ids[index]];
    refocus.current = { id: movedId, direction };
    order.mutate({ ids, movedId });
  };
  useEffect(() => {
    const target = refocus.current;
    if (!target || order.isPending) return;
    refocus.current = null;
    focusMoveButton(`activity-${target.id}`, target.direction);
  }, [list.data, order.isPending]);
  const generating = Boolean(jobId) || generate.isPending;

  return (
    <section aria-labelledby={`activities-${module.id}`} className="space-y-4 border-t border-border pt-6">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <h3 id={`activities-${module.id}`} className="font-display text-xl font-medium">
          <span className="mr-2 text-accent">{twoDigits(module.order)}</span>
          {module.title}
        </h3>
        <div className="flex flex-wrap gap-2">
          <Button
            variant="outline"
            size="sm"
            loading={generating}
            onClick={async () => {
              const drafts = activities.filter((activity) => activity.status === "draft").length;
              const ok =
                !drafts ||
                (await confirm({
                  title: "¿Regenerar con IA?",
                  description:
                    "Las propuestas de la IA que nadie editó se reemplazan; lo publicado y lo que editaste se queda.",
                  confirmLabel: "Regenerar",
                }));
              if (ok) generate.mutate();
            }}
          >
            <Sparkles />{" "}
            {generating
              ? job.data?.step || "La IA está diseñando…"
              : activities.length
                ? "Regenerar con IA"
                : "Generar con IA"}
          </Button>
          <DropdownMenu>
            <DropdownMenuTrigger asChild>
              <Button size="sm" disabled={activities.length >= 6}>
                <Plus /> Agregar
              </Button>
            </DropdownMenuTrigger>
            <DropdownMenuContent align="end">
              {TYPES.map((type) => (
                <DropdownMenuItem key={type} onSelect={() => create.mutate(type)}>
                  {ACTIVITY_LABELS[type]}
                </DropdownMenuItem>
              ))}
            </DropdownMenuContent>
          </DropdownMenu>
        </div>
      </div>

      {list.isPending ? (
        <Skeleton className="h-20" />
      ) : activities.length === 0 ? (
        <p className="text-sm text-muted-foreground">Sin actividades: genera una propuesta con IA o agrega una.</p>
      ) : (
        <ol className="space-y-2" aria-label={`Actividades de ${module.title}`}>
          {activities.map((activity, index) => {
            const ready = activity.status === "ready";
            const cannotPublish = !ready && activity.problems.length > 0;
            const PublishIcon = ready ? EyeOff : Eye;
            const publishLabel = ready ? "Despublicar" : "Publicar";
            return (
              <li key={activity.id} className="flex flex-wrap items-center gap-3 border border-border bg-white px-4 py-3">
                <div className="min-w-0 flex-1">
                  <p className="text-[11px] font-bold uppercase tracking-label text-muted-foreground">
                    {ACTIVITY_LABELS[activity.type]} ·{" "}
                    <span className={ready ? "text-success" : "text-warning"}>{ready ? "Publicada" : "Borrador"}</span>
                    {ready && (
                      <>
                        {" · "}
                        <Volume2 className="inline h-3 w-3" /> {VOICE[activity.voice_status]}
                        {activity.voice_status === "failed" && (
                          <button
                            type="button"
                            className="-my-3 ml-1 inline-flex min-h-10 items-center underline"
                            onClick={() => void activitiesApi.voice(activity.id).then(refresh, toastError)}
                          >
                            Reintentar
                          </button>
                        )}
                      </>
                    )}
                  </p>
                  <p className="font-semibold">{activity.title}</p>
                  {activity.problems.length > 0 && (
                    <p className="mt-1 flex items-start gap-1 text-xs text-warning">
                      <AlertTriangle className="mt-0.5 h-3 w-3 shrink-0" /> {activity.problems.join(" ")}
                    </p>
                  )}
                </div>
                {/* On a phone: the arrows, "Probar" and a menu with the rest (unpublishing and deleting never sit
                    right under a finger trying the game). */}
                <div className="flex w-full flex-wrap items-center gap-1 sm:w-auto">
                  <MoveButtons
                    id={`activity-${activity.id}`}
                    label={activity.title}
                    index={index}
                    total={activities.length}
                    busy={order.isPending}
                    onMove={(direction) => move(index, direction)}
                  />
                  <Button
                    variant="ghost"
                    size="sm"
                    className="ml-auto sm:ml-0"
                    onClick={() => setTrying({ activity, session: Date.now() })}
                  >
                    <Play /> Probar
                  </Button>
                  <Button
                    variant="ghost"
                    size="sm"
                    className="hidden sm:inline-flex"
                    onClick={() => setEditing(activity)}
                    aria-label={`Editar ${activity.title}`}
                  >
                    <Pencil /> Editar
                  </Button>
                  <Button
                    variant={ready ? "ghost" : "accent"}
                    size="sm"
                    className="hidden sm:inline-flex"
                    disabled={cannotPublish}
                    onClick={() => void toggleStatus(activity)}
                    aria-label={`${publishLabel} ${activity.title}`}
                  >
                    <PublishIcon /> {publishLabel}
                  </Button>
                  <Button
                    variant="ghost"
                    size="icon-sm"
                    className="hidden sm:inline-flex"
                    aria-label={`Eliminar ${activity.title}`}
                    onClick={() => remove(activity)}
                  >
                    <Trash2 />
                  </Button>
                  <DropdownMenu>
                    <DropdownMenuTrigger asChild>
                      <Button variant="ghost" size="icon" className="sm:hidden" aria-label={`Más acciones para ${activity.title}`}>
                        <MoreHorizontal />
                      </Button>
                    </DropdownMenuTrigger>
                    <DropdownMenuContent>
                      <DropdownMenuItem onSelect={() => setEditing(activity)}>
                        <Pencil /> Editar
                      </DropdownMenuItem>
                      <DropdownMenuItem disabled={cannotPublish} onSelect={() => void toggleStatus(activity)}>
                        <PublishIcon /> {publishLabel}
                      </DropdownMenuItem>
                      <DropdownMenuItem destructive onSelect={() => void remove(activity)}>
                        <Trash2 /> Eliminar
                      </DropdownMenuItem>
                    </DropdownMenuContent>
                  </DropdownMenu>
                </div>
              </li>
            );
          })}
        </ol>
      )}
      <p aria-live="polite" className="sr-only">
        {moved}
      </p>

      {editing && (
        <ActivityEditor
          key={editing.id}
          courseId={courseId}
          activity={editing}
          onClose={() => setEditing(null)}
          onSaved={() => {
            void refresh();
            setEditing(null);
          }}
        />
      )}
      {trying && (
        <ActivityPreview
          key={trying.session}
          activity={trying.activity}
          language={language}
          onClose={() => setTrying(null)}
        />
      )}
    </section>
  );
}

interface ActivityEditorProps {
  courseId: number;
  activity: ActivityAdmin;
  onClose: () => void;
  onSaved: () => void;
}

function ActivityEditor({ courseId, activity, onClose, onSaved }: ActivityEditorProps) {
  const [title, setTitle] = useState(activity.title);
  const [intro, setIntro] = useState(activity.intro);
  // An inspection saved in the earlier format (zones on a picture) starts over from the template.
  const [spec, setSpec] = useState<AnySpec>(() =>
    activity.type === "inspection" && !("items" in activity.spec)
      ? TEMPLATES.inspection.spec
      : (activity.spec as unknown as AnySpec),
  );
  const [imageUrl, setImageUrl] = useState(activity.image_url);
  const { upload, busy: uploading } = useUpload();
  const [waitingPicture, setWaitingPicture] = useState(false);
  const fileInput = useRef<HTMLInputElement>(null);
  const confirm = useConfirm();
  const alive = useRef(true);
  useEffect(() => {
    alive.current = true; // StrictMode mounts, unmounts and mounts again
    return () => {
      alive.current = false;
    };
  }, []);
  const dirty =
    title !== activity.title || intro !== activity.intro || JSON.stringify(spec) !== JSON.stringify(activity.spec);
  const close = async () => {
    if (dirty && !(await confirm({ title: "¿Descartar los cambios?", confirmLabel: "Descartar", destructive: true })))
      return;
    onClose();
  };
  const save = useMutation({
    mutationFn: () =>
      activitiesApi.update(activity.id, { title, intro, spec: spec as unknown as Record<string, unknown> }),
    onSuccess: () => {
      toast.success("Actividad guardada");
      onSaved();
    },
    onError: toastError,
  });

  const choosePicture = async (file: File) => {
    setWaitingPicture(true);
    try {
      const asset = await upload(file, { kind: "image", courseId, purpose: "course_material" });
      if (!asset) return;
      // The picture is checked after the upload: wait (a few seconds at most) while the server says it isn't ready.
      for (let attempt = 0; attempt < 15 && alive.current; attempt += 1) {
        try {
          const updated = await activitiesApi.setImage(activity.id, asset.id);
          if (!alive.current) return;
          setImageUrl(updated.image_url);
          toast.success("Foto de referencia lista.");
          return;
        } catch (error) {
          if (!(error instanceof ApiError && error.status === 422)) throw error;
          await new Promise((resolve) => window.setTimeout(resolve, 2000));
        }
      }
      if (alive.current) toast.error("La imagen no quedó lista. Intenta de nuevo.");
    } catch (error) {
      if (alive.current) toastError(error);
    } finally {
      if (alive.current) setWaitingPicture(false);
    }
  };

  return (
    <Sheet open onOpenChange={(open) => !open && void close()}>
      <SheetContent className="w-full sm:max-w-3xl">
        <SheetHeader>
          <SheetTitle>{ACTIVITY_LABELS[activity.type]}</SheetTitle>
          <SheetDescription>Al guardar, el servidor revisa que la actividad se pueda jugar.</SheetDescription>
        </SheetHeader>
        <SheetBody className="space-y-5">
          <div>
            <Label htmlFor="activity-title">Título</Label>
            <Input
              id="activity-title"
              value={title}
              maxLength={200}
              onChange={(event) => setTitle(event.target.value)}
            />
          </div>
          <div>
            <Label htmlFor="activity-intro">Introducción (se dice con voz)</Label>
            <Textarea
              id="activity-intro"
              value={intro}
              maxLength={600}
              onChange={(event) => setIntro(event.target.value)}
            />
          </div>
          {activity.type === "inspection" && (
            <div>
              <input
                ref={fileInput}
                type="file"
                accept="image/png,image/jpeg,image/webp"
                className="hidden"
                onChange={(event) => {
                  const file = event.target.files?.[0];
                  if (file) void choosePicture(file);
                  event.target.value = "";
                }}
              />
              <Button
                type="button"
                variant="outline"
                size="sm"
                onClick={() => fileInput.current?.click()}
                loading={uploading || waitingPicture}
              >
                <ImageUp /> {imageUrl ? "Cambiar foto de referencia" : "Foto de referencia (opcional)"}
              </Button>
            </div>
          )}
          <ActivityForm type={activity.type} spec={spec} onChange={setSpec} />
        </SheetBody>
        <SheetFooter>
          <Button variant="ghost" onClick={() => void close()}>
            Cancelar
          </Button>
          <Button onClick={() => save.mutate()} loading={save.isPending}>
            Guardar
          </Button>
        </SheetFooter>
      </SheetContent>
    </Sheet>
  );
}
